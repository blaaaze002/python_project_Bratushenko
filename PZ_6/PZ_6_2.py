#Дан список A размера N и целые числа K и L (1 < K < L < N). Переставить в обратном порядке элементы списка, расположенные между элементами Aₖ и Aₗ, включая эти элементы#
N = int(input("Введите размер списка: "))

A = []

for i in range(N):
    A.append(int(input("Введите элемент: ")))

K = int(input("Введите K: "))
L = int(input("Введите L: "))

A[K-1:L] = A[K-1:L][::-1]

print(A)


