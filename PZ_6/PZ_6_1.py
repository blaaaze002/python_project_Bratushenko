#Дано целое число N (>2). Сформировать и вывести целочисленный список размера 10, содержащий 10 первых элементов последовательности чисел Фибоначчи Fₖ: F₁ = 1, F₂ = 1, Fₖ = Fₖ₋₂ + Fₖ₋₁, K = 3, 4, ...#

N = int(input("Введите N: "))

if N > 2:
    A = [1, 1]

    while len(A) < 10:
        A.append(A[-1] + A[-2])

    print(A)
else:
    print("N должно быть больше 2")

