# 2. Мастям игральных карт присвоены порядковые номера: 1– пики, 2 – трефы, 3 –
# бубны, 4 – червы. Достоинству карт, старших десятки, присвоены номера: 11 – валет,
# 12 – дама, 13 – король, 14 – туз. Дано трехзначное число, в котором первая цифра
# указывает на масть, а вторые две на достоинство карты. Вывести соответствующее
# название карты вида «дама червей», «туз треф» и т.п.

num = int(input("Введите трёхзначное число:"))
masts = ["пик", "треф", "бубен", "червей"]
cards = {
            6: "шестёрка",
            7: "семёрка",
            8: "восьмёрка",
            9: "девятка",
            10: "десятка",
            11: "валет",
            12: "дама",
            13: "король",
            14: "туз"
        }

mast = num // 100
card = num % 100
while True:
    try:
        if num < 106 or num > 414:
            print("Неверное число")
            continue

        if mast < 1 or mast > 4 or card < 6 or card > 14:
            print("Такой карты нет")
            continue

        print(cards[card], masts[mast - 1])
        break

    except ValueError:
        print("Введите целое число!")