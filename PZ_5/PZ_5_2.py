#Описать функцию DigitCountSum(K, C, S), находящую количество C цифр целого положительного числа K,
#а также их сумму S (K — входной, C и S — выходные параметры целого типа). #
#С помощью этой функции найти количество и сумму цифр для каждого из пяти данных целых чисел.#
def DigitCountSum(K):
    C = 0
    S = 0

    while K > 0:
        digit = K % 10
        S += digit
        C +=  1
        K //= 10
    return S,C

for i in range(5):
    K = int(input("Введите целое число: "))

    C, S = DigitCountSum(K)

    print("Количество цифр:",  C)
    print("Сумма цифр:",  S)